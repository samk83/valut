"""Download the site's web fonts into assets/fonts/ so visitors never contact a third party.

Latin families (Fraunces, Inter, IBM Plex Mono) are saved in full latin/latin-ext subsets.
Korean families (Noto Sans KR, Noto Serif KR) are cut down to the characters used in the
site's HTML files, so run this again after changing Korean copy:

    python website/tools/fetch_fonts.py

All fonts are licensed under the SIL Open Font License 1.1.
"""
import hashlib
import pathlib
import re
import urllib.parse
import urllib.request

SITE = pathlib.Path(__file__).resolve().parent.parent
OUT = SITE / "assets" / "fonts"
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36"
LATIN = [
    "Fraunces:ital,opsz,wght@0,9..144,300..600;1,9..144,300..400",
    "Inter:wght@400..600",
    "IBM Plex Mono:wght@400;500",
]
OFL_URL = "https://raw.githubusercontent.com/googlefonts/noto-cjk/main/Sans/LICENSE"
KOREAN = [
    "Noto Sans KR:wght@400;500;700",
    "Noto Serif KR:wght@300;400;600",
]


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def css_for(family, text=None):
    q = "family=" + urllib.parse.quote(family, safe=":,@;.") + "&display=swap"
    if text:
        q += "&text=" + urllib.parse.quote(text)
    return get("https://fonts.googleapis.com/css2?" + q).decode()


def localize(css):
    def repl(m):
        url = m.group(1)
        data = get(url)
        name = hashlib.sha1(url.encode()).hexdigest()[:16] + ".woff2"
        (OUT / name).write_bytes(data)
        return "url(" + name + ")"
    return re.sub(r"url\((https://fonts\.gstatic\.com/[^)]+)\)", repl, css)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    old_files = set(OUT.glob("*.woff2"))
    chars = set()
    for pattern in ("*.html", "*.js", "*.css"):
        for page in SITE.rglob(pattern):
            chars.update(c for c in page.read_text(encoding="utf-8") if c.isprintable())
    text = "".join(sorted(chars))
    parts = ["/* Generated by tools/fetch_fonts.py. Fonts: SIL Open Font License 1.1. */"]
    for fam in LATIN:
        css = css_for(fam)
        blocks = re.findall(r"/\* (latin(?:-ext)?) \*/\s*(@font-face \{.*?\})", css, re.S)
        parts += [b for _, b in blocks]
    for fam in KOREAN:
        parts.append(css_for(fam, text))
    css = localize("\n".join(parts))
    (OUT / "fonts.css").write_text(css, encoding="utf-8")
    (OUT / "OFL.txt").write_bytes(get(OFL_URL))
    for old in old_files:
        if old.name not in css:
            old.unlink()
    total = sum(f.stat().st_size for f in OUT.glob("*.woff2"))
    print(f"{len(list(OUT.glob('*.woff2')))} font files, {total // 1024} KB")


if __name__ == "__main__":
    main()
